import { test, expect } from '@playwright/test'
const reply=(route,data)=>route.fulfill({json:{success:true,data}})
async function setup(page) {
  await page.route('http://localhost:8086/api/v1/auth/me',route=>reply(route,{organization:{type:'BORROWER',name:'Borrower fund',platformOrganizationId:77},user:{fullName:'Admin'}}))
  await page.route('http://localhost:8081/**',route=>reply(route,[]))
  const agreement={id:2,lenderId:6,coverageRatio:1.05,feeRate:0.03,collateralRules:[{assetType:'CASH',haircut:0},{assetType:'SECURITY',securityId:3,haircut:0.1},{assetType:'SECURITY',securityId:4,haircut:0.2}]}
  await page.route('**/organizations/77/reservations?*',route=>reply(route,{content:[{id:8,locateId:5,mslaId:2,securityId:1,quantity:10,remainingQuantity:10,status:'ACTIVE',expiresAt:new Date(Date.now()+86400000).toISOString()}],totalPages:1}))
  await page.route('**/organizations/77/agreements?*',route=>reply(route,{content:[agreement],totalPages:1}))
  await page.route('**/organizations/77/agreements/2',route=>reply(route,agreement))
  await page.route('**/organizations/77/lenders',route=>reply(route,[{id:6,name:'Lender firm'}]))
  await page.route('**/api/v1/securities',route=>reply(route,[{id:1,symbol:'TCS',price:100},{id:3,symbol:'INFY',price:100},{id:4,symbol:'RELIANCE',price:200}]))
  const options=[{key:'CASH',assetType:'CASH',symbol:'Cash',haircut:0,unitPrice:1,available:2000},{key:'SECURITY:3',assetType:'SECURITY',securityId:3,symbol:'INFY',haircut:0.1,unitPrice:100,available:5},{key:'SECURITY:4',assetType:'SECURITY',securityId:4,symbol:'RELIANCE',haircut:0.2,unitPrice:200,available:4}]
  await page.route('**/organizations/77/loans/collateral-preview',route=>{
    const body=route.request().postDataJSON(),required=body.quantity*100*1.05
    const usage={};body.collateral.forEach(row=>{const key=row.assetType==='CASH'?'CASH':`SECURITY:${row.securityId}`;usage[key]=(usage[key]||0)+(row.assetType==='CASH'?row.cashAmount:row.quantity)})
    const rows=body.collateral.map((row,index)=>{const key=row.assetType==='CASH'?'CASH':`SECURITY:${row.securityId}`,option=options.find(o=>o.key===key),units=row.assetType==='CASH'?row.cashAmount:row.quantity;const errors=[];if(!units)errors.push('Enter a positive allocation');if(usage[key]>option.available)errors.push(`Combined allocations exceed available ${option.symbol}`);return {index,unitPrice:option.unitPrice,haircut:option.haircut,available:option.available,marketValue:units*option.unitPrice,eligibleValue:units*option.unitPrice*(1-option.haircut),errors}})
    const marketValue=rows.reduce((sum,row)=>sum+row.marketValue,0),eligibleValue=rows.reduce((sum,row)=>sum+row.eligibleValue,0),shortfall=Math.max(0,required-eligibleValue),errors=rows.flatMap(row=>row.errors)
    if(shortfall>0)errors.push('Eligible collateral does not cover the loan requirement')
    return reply(route,{options,rows,loanMarketValue:body.quantity*100,requiredCollateral:required,coverageRatio:1.05,marketValue,eligibleValue,shortfall,surplus:Math.max(0,eligibleValue-required),coveragePercent:eligibleValue/(body.quantity*100)*100,eligible:body.collateral.length>0&&!errors.length,errors})
  })
  const submitted=[]
  await page.route('**/organizations/77/loans',route=>{submitted.push(route.request().postDataJSON());return reply(route,{id:50})})
  await page.goto('http://localhost:5173/reservations')
  await page.getByRole('button',{name:'Convert to loan',exact:true}).first().click()
  return {submitted}
}
test('loan request mixes cash and securities and displays their market and eligible values',async({page})=>{
  const state=await setup(page),dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('button',{name:'Submit loan request'})).toBeDisabled()
  await dialog.getByRole('button',{name:'Add collateral',exact:true}).click()
  await dialog.getByLabel('Cash amount 1',{exact:true}).fill('300')
  await dialog.getByRole('button',{name:'Add collateral',exact:true}).click()
  await dialog.getByLabel('Collateral asset 2',{exact:true}).selectOption('SECURITY:3')
  await dialog.getByLabel('Security quantity 2',{exact:true}).fill('5')
  await dialog.getByRole('button',{name:'Add collateral',exact:true}).click()
  await dialog.getByLabel('Collateral asset 3',{exact:true}).selectOption('SECURITY:4')
  await dialog.getByLabel('Security quantity 3',{exact:true}).fill('2')
  await expect(dialog.getByRole('status')).toHaveText('Coverage sufficient')
  const table=dialog.getByRole('table',{name:'Proposed collateral allocations'})
  await expect(table.locator('tbody tr').nth(1)).toContainText('₹500.00')
  await expect(table.locator('tbody tr').nth(1)).toContainText('₹450.00')
  await expect(table.locator('tbody tr').nth(2)).toContainText('₹320.00')
  await expect(table.locator('tfoot')).toContainText('₹1,200.00')
  await expect(table.locator('tfoot')).toContainText('₹1,070.00')
  await dialog.getByLabel('Loan maturity (IST)',{exact:true}).fill(new Date(Date.now()+86400000).toISOString().slice(0,16))
  await dialog.getByRole('button',{name:'Submit loan request'}).click()
  await expect(dialog).toHaveCount(0)
  expect(state.submitted).toHaveLength(1)
  expect(state.submitted[0].collateral).toEqual([{assetType:'CASH',securityId:null,quantity:0,cashAmount:300},{assetType:'SECURITY',securityId:3,quantity:5,cashAmount:0},{assetType:'SECURITY',securityId:4,quantity:2,cashAmount:0}])
  expect(new Date(state.submitted[0].maturityAt).getTime()).toBeGreaterThan(Date.now())
})
test('repeated assets cannot exceed available holdings and removing a lot recalculates coverage',async({page})=>{
  const state=await setup(page),dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Add collateral',exact:true}).click()
  await dialog.getByLabel('Cash amount 1',{exact:true}).fill('1100')
  for(const index of [2,3]){await dialog.getByRole('button',{name:'Add collateral',exact:true}).click();await dialog.getByLabel(`Collateral asset ${index}`,{exact:true}).selectOption('SECURITY:3');await dialog.getByLabel(`Security quantity ${index}`,{exact:true}).fill('3')}
  await expect(dialog).toContainText('Combined allocations exceed available INFY')
  await expect(dialog.getByRole('button',{name:'Submit loan request'})).toBeDisabled()
  await dialog.getByRole('button',{name:'Remove collateral 3',exact:true}).click()
  await expect(dialog.getByRole('status')).toHaveText('Coverage sufficient')
  await dialog.getByLabel('Cash amount 1',{exact:true}).fill('100')
  await expect(dialog.getByRole('status')).toHaveText('Coverage incomplete')
  expect(state.submitted).toHaveLength(0)
})
test('multi-collateral table scrolls inside the dialog on a narrow screen',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await setup(page)
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Add collateral',exact:true}).click()
  const bounds=await dialog.evaluate(el=>({width:el.getBoundingClientRect().width,scroll:el.scrollWidth,client:el.clientWidth}))
  expect(bounds.width).toBeLessThanOrEqual(390)
  expect(bounds.scroll).toBeLessThanOrEqual(bounds.client+1)
  await expect(dialog.getByRole('button',{name:'Submit loan request'})).toBeVisible()
})
