test('buy-in drafts validate remaining quantity and preserve execution without sending an order', async ({ page }) => {
  const posts = []
  page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
  await openPreview(page)
  await page.getByRole('button', { name: 'Manage buy-in', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Remaining order quantity')).toHaveValue('400')
  await dialog.getByLabel('Remaining order quantity').fill('401')
  await dialog.getByRole('button', { name: 'Save buy-in draft' }).click()
  await expect(dialog.getByRole('alert')).toContainText('from 1 to 400')
  await dialog.getByLabel('Remaining order quantity').fill('250')
  await dialog.getByLabel('Limit price (INR)').fill('1500')
  await dialog.getByRole('button', { name: 'Save buy-in draft' }).click()
  await expect(page.getByRole('status')).toContainText('No backend request was sent')
  await expect(workspace(page)).toContainText('draft for 250 remaining')
  await expect(page.getByRole('progressbar', { name: 'Buy-in filled' })).toHaveAttribute('value', '60')
  await page.getByRole('button', { name: 'Manage buy-in', exact: true }).click()
  await expect(dialog.getByLabel('Remaining order quantity')).toHaveValue('250')
  await dialog.getByLabel('Limit price (INR)').fill('1.234')
  await dialog.getByRole('button', { name: 'Save buy-in draft' }).click()
  await expect(dialog.getByRole('alert')).toContainText('two decimal places')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Manage buy-in', exact: true })).toBeFocused()
  expect(posts).toEqual([])
  await page.reload()
  await expect(workspace(page)).not.toContainText('draft for 250 remaining')
})

