test('notice preparation stays a draft and CSV export follows filters', async ({ page }) => {
  await openPreview(page)
  await page.getByRole('button', { name: 'Prepare notice', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Notice type').selectOption('Buy-in intent')
  await dialog.getByLabel('Message', { exact: true }).fill('Please return the outstanding securities.')
  await dialog.getByRole('button', { name: 'Save notice draft' }).click()
  await expect(workspace(page)).toContainText('Please return the outstanding securities.')
  await expect(workspace(page)).toContainText('Not sent')
  await page.getByLabel('Security or reference', { exact: true }).fill('INFY')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  const pendingDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export', exact: false }).click()
  const download = await pendingDownload
  const csv = await readFile(await download.path(), 'utf8')
  expect(csv).toContain('Exposure INR')
  expect(csv).toContain('INFY')
  expect(csv).not.toContain('HDFCBANK')
  expect(download.suggestedFilename()).toBe('lenddesk-defaults-buyins-sample.csv')
})
