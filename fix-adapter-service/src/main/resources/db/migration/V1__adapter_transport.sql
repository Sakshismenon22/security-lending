CREATE TABLE adapter_identity (
 id INTEGER PRIMARY KEY CHECK(id=1), side VARCHAR(20) NOT NULL, institution_id VARCHAR(100) NOT NULL,
 sender_comp_id VARCHAR(64) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE outbound_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id VARCHAR(120) NOT NULL UNIQUE, event_type VARCHAR(80) NOT NULL,
 organization_id BIGINT NOT NULL, reference_id BIGINT NOT NULL,
 message_kind VARCHAR(20) NOT NULL, session_key VARCHAR(240) NOT NULL,
 counterparty_id VARCHAR(100) NOT NULL, payload TEXT NOT NULL, payload_hash VARCHAR(64) NOT NULL,
 state VARCHAR(30) NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, last_sent_at TIMESTAMP WITH TIME ZONE,
 acknowledged_at TIMESTAMP WITH TIME ZONE, last_error VARCHAR(1000),
 source_topic VARCHAR(200) NOT NULL, source_partition INTEGER NOT NULL, source_offset BIGINT NOT NULL,
 row_version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_outbound_session ON outbound_message(session_key,id,state);
CREATE TABLE inbound_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id VARCHAR(120) NOT NULL UNIQUE, event_type VARCHAR(80) NOT NULL,
 organization_id BIGINT NOT NULL, reference_id BIGINT NOT NULL,
 message_kind VARCHAR(20) NOT NULL, session_key VARCHAR(240) NOT NULL,
 counterparty_id VARCHAR(100) NOT NULL, payload TEXT NOT NULL, payload_hash VARCHAR(64) NOT NULL,
 received_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE kafka_publication (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inbound_message_id BIGINT NOT NULL UNIQUE REFERENCES inbound_message(id),
 event_id VARCHAR(120) NOT NULL UNIQUE, topic VARCHAR(200) NOT NULL,
 partition_key VARCHAR(80) NOT NULL, payload TEXT NOT NULL,
 state VARCHAR(30) NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, published_at TIMESTAMP WITH TIME ZONE,
 last_error VARCHAR(1000), row_version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_publication_pending ON kafka_publication(state,id);
