CREATE TABLE short_lot (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id), security_id BIGINT NOT NULL REFERENCES security_master(id),
 order_id BIGINT NOT NULL REFERENCES trade_order(id), open_quantity BIGINT NOT NULL CHECK(open_quantity >= 0),
 price NUMERIC(24,6) NOT NULL
);
