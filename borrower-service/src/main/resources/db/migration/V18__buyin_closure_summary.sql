CREATE TABLE buyin_closure_summary (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id),
 quantity BIGINT NOT NULL CHECK(quantity>0),
 purchase_value NUMERIC(24,6) NOT NULL,
 execution_costs NUMERIC(24,6) NOT NULL,
 purchase_cost NUMERIC(24,6) NOT NULL,
 cash_collateral_applied NUMERIC(24,6) NOT NULL,
 cash_collateral_returned NUMERIC(24,6) NOT NULL,
 average_price NUMERIC(24,6) NOT NULL,
 reference VARCHAR(120) NOT NULL,
 closed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(organization_id,loan_id)
);
