CREATE TABLE organization (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, registration_number VARCHAR(100) NOT NULL UNIQUE,
 currency VARCHAR(3) NOT NULL DEFAULT 'INR', created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id), name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL, role VARCHAR(40) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(organization_id,email)
);
CREATE TABLE trader_account (
 organization_id BIGINT PRIMARY KEY REFERENCES organization(id),
 available NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK(available >= 0),
 blocked NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK(blocked >= 0),
 pledged NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK(pledged >= 0)
);
CREATE TABLE lender_reference (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, external_id VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE security_master (
 id BIGINT PRIMARY KEY, symbol VARCHAR(40) NOT NULL, exchange VARCHAR(30) NOT NULL,
 name VARCHAR(160) NOT NULL, isin VARCHAR(20), currency VARCHAR(3) NOT NULL,
 price NUMERIC(24,6), price_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(symbol,exchange)
);
CREATE TABLE holdings (
 organization_id BIGINT NOT NULL REFERENCES organization(id), security_id BIGINT NOT NULL REFERENCES security_master(id),
 owned_quantity BIGINT NOT NULL DEFAULT 0 CHECK(owned_quantity >= 0),
 borrowed_quantity BIGINT NOT NULL DEFAULT 0 CHECK(borrowed_quantity >= 0),
 pledged_quantity BIGINT NOT NULL DEFAULT 0 CHECK(pledged_quantity >= 0),
 blocked_owned BIGINT NOT NULL DEFAULT 0 CHECK(blocked_owned >= 0),
 blocked_borrowed BIGINT NOT NULL DEFAULT 0 CHECK(blocked_borrowed >= 0),
 average_cost NUMERIC(24,6) NOT NULL DEFAULT 0, realized_pnl NUMERIC(24,6) NOT NULL DEFAULT 0,
 PRIMARY KEY(organization_id,security_id),
 CHECK(owned_quantity >= pledged_quantity + blocked_owned), CHECK(borrowed_quantity >= blocked_borrowed)
);
CREATE TABLE msla (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 lender_id BIGINT NOT NULL REFERENCES lender_reference(id), number VARCHAR(100) NOT NULL UNIQUE,
 status VARCHAR(30) NOT NULL, effective_date DATE NOT NULL, expiry_date DATE NOT NULL,
 credit_limit NUMERIC(24,6) NOT NULL CHECK(credit_limit > 0), fee_rate NUMERIC(16,10) NOT NULL CHECK(fee_rate >= 0),
 rebate_rate NUMERIC(16,10) NOT NULL CHECK(rebate_rate >= 0), coverage_ratio NUMERIC(12,6) NOT NULL CHECK(coverage_ratio >= 1),
 billing_frequency VARCHAR(20) NOT NULL, day_basis INTEGER NOT NULL CHECK(day_basis IN (360,365)),
 recall_allowed BOOLEAN NOT NULL, margin_hours INTEGER NOT NULL CHECK(margin_hours > 0),
 recall_hours INTEGER NOT NULL CHECK(recall_hours > 0), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(expiry_date >= effective_date)
);
CREATE TABLE collateral_haircut (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, msla_id BIGINT NOT NULL REFERENCES msla(id),
 asset_type VARCHAR(20) NOT NULL, security_id BIGINT REFERENCES security_master(id),
 haircut NUMERIC(12,8) NOT NULL CHECK(haircut >= 0 AND haircut < 1),
 CHECK((asset_type='CASH' AND security_id IS NULL AND haircut=0) OR (asset_type='SECURITY' AND security_id IS NOT NULL))
);
CREATE TABLE locate_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id), security_id BIGINT NOT NULL REFERENCES security_master(id),
 quantity BIGINT NOT NULL CHECK(quantity > 0), approved_quantity BIGINT NOT NULL DEFAULT 0,
 status VARCHAR(30) NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 locate_id BIGINT NOT NULL UNIQUE REFERENCES locate_request(id), msla_id BIGINT NOT NULL REFERENCES msla(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id), quantity BIGINT NOT NULL CHECK(quantity > 0),
 remaining_quantity BIGINT NOT NULL CHECK(remaining_quantity >= 0), status VARCHAR(30) NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE loan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id), reservation_id BIGINT NOT NULL REFERENCES reservation(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id), quantity BIGINT NOT NULL CHECK(quantity > 0),
 outstanding_quantity BIGINT NOT NULL CHECK(outstanding_quantity >= 0), status VARCHAR(30) NOT NULL,
 fee_rate NUMERIC(16,10) NOT NULL, rebate_rate NUMERIC(16,10) NOT NULL, coverage_ratio NUMERIC(12,6) NOT NULL,
 day_basis INTEGER NOT NULL, billing_frequency VARCHAR(20) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 settled_at TIMESTAMP WITH TIME ZONE, closed_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE collateral_position (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), asset_type VARCHAR(20) NOT NULL,
 security_id BIGINT REFERENCES security_master(id), quantity BIGINT NOT NULL DEFAULT 0 CHECK(quantity >= 0),
 cash_amount NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK(cash_amount >= 0), haircut NUMERIC(12,8) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'POSTED',
 CHECK((asset_type='CASH' AND security_id IS NULL AND quantity=0) OR (asset_type='SECURITY' AND security_id IS NOT NULL AND cash_amount=0))
);
CREATE TABLE collateral_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), position_id BIGINT NOT NULL REFERENCES collateral_position(id),
 type VARCHAR(30) NOT NULL, amount NUMERIC(24,6) NOT NULL, quantity BIGINT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE loan_return (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), quantity BIGINT NOT NULL CHECK(quantity > 0),
 owned_quantity BIGINT NOT NULL, borrowed_quantity BIGINT NOT NULL, status VARCHAR(30) NOT NULL,
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, settled_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE trade_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id), side VARCHAR(10) NOT NULL, type VARCHAR(10) NOT NULL,
 source VARCHAR(20) NOT NULL, quantity BIGINT NOT NULL CHECK(quantity > 0), limit_price NUMERIC(24,6),
 reserved_cash NUMERIC(24,6) NOT NULL DEFAULT 0, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, filled_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE trade_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 order_id BIGINT NOT NULL UNIQUE REFERENCES trade_order(id), security_id BIGINT NOT NULL REFERENCES security_master(id),
 side VARCHAR(10) NOT NULL, source VARCHAR(20) NOT NULL, quantity BIGINT NOT NULL,
 price NUMERIC(24,6) NOT NULL, value NUMERIC(24,6) NOT NULL, price_at TIMESTAMP WITH TIME ZONE NOT NULL,
 executed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE trader_account_transaction (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 type VARCHAR(40) NOT NULL, amount NUMERIC(24,6) NOT NULL, balance_after NUMERIC(24,6) NOT NULL,
 reference VARCHAR(120) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE loan_default (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL UNIQUE REFERENCES loan(id), obligation_id BIGINT NOT NULL, obligation_type VARCHAR(20) NOT NULL,
 reason VARCHAR(500) NOT NULL, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE buy_in (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 default_id BIGINT NOT NULL UNIQUE REFERENCES loan_default(id), quantity BIGINT NOT NULL,
 price NUMERIC(24,6) NOT NULL, costs NUMERIC(24,6) NOT NULL, collateral_applied NUMERIC(24,6) NOT NULL,
 residual_balance NUMERIC(24,6) NOT NULL, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 type VARCHAR(80) NOT NULL, reference VARCHAR(120) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE outbox_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 event_type VARCHAR(80) NOT NULL, aggregate_id VARCHAR(120) NOT NULL, payload TEXT NOT NULL,
 published BOOLEAN NOT NULL DEFAULT FALSE, 
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE inbox_event (event_id VARCHAR(120) PRIMARY KEY, received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX ix_loan_org ON loan(organization_id,status);
CREATE INDEX ix_order_org ON trade_order(organization_id,status);

CREATE INDEX ix_outbox_pending ON outbox_event(published,id);
