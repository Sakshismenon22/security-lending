-- Calculations, obligations and recoveries originate in other services. These are borrower read models.
CREATE TABLE loan_valuation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), valued_at TIMESTAMP WITH TIME ZONE NOT NULL,
 loan_market_value NUMERIC(24,6) NOT NULL, required_collateral NUMERIC(24,6) NOT NULL,
 recognized_collateral NUMERIC(24,6) NOT NULL, coverage_ratio NUMERIC(12,6) NOT NULL, shortfall NUMERIC(24,6) NOT NULL,
 source_event_id VARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE payment_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 fee_id BIGINT REFERENCES lending_fee(id), type VARCHAR(30) NOT NULL, amount NUMERIC(24,6) NOT NULL CHECK(amount>0),
 client_request_id VARCHAR(120) NOT NULL, status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 confirmed_at TIMESTAMP WITH TIME ZONE, UNIQUE(organization_id,client_request_id)
);
CREATE TABLE fee_accrual_view (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), accrual_date DATE NOT NULL, type VARCHAR(20) NOT NULL,
 amount NUMERIC(24,6) NOT NULL, base_value NUMERIC(24,6) NOT NULL, rate NUMERIC(16,10) NOT NULL,
 source_event_id VARCHAR(120) NOT NULL UNIQUE, UNIQUE(loan_id,accrual_date,type)
);
CREATE TABLE projection_cursor (
 resource VARCHAR(80) NOT NULL, reference_id BIGINT NOT NULL, version BIGINT NOT NULL,
 PRIMARY KEY(resource,reference_id)
);
