-- ER entities plus operational fields needed to distinguish requests, settlement, and accounting.
CREATE TABLE role (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_name VARCHAR(40) NOT NULL UNIQUE);
INSERT INTO role(role_name) VALUES ('ADMIN'),('TRADER'),('TREASURY'),('OPERATIONS'),('READ_ONLY');
ALTER TABLE users ADD COLUMN role_id BIGINT REFERENCES role(id);
UPDATE users SET role_id=(SELECT id FROM role WHERE role_name=users.role);
ALTER TABLE users DROP COLUMN role;
ALTER TABLE users ALTER COLUMN role_id SET NOT NULL;
CREATE TABLE assets (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_name VARCHAR(40) NOT NULL UNIQUE);
INSERT INTO assets(asset_name) VALUES ('CASH'),('SECURITY');
ALTER TABLE collateral_position ADD COLUMN asset_id BIGINT REFERENCES assets(id);
ALTER TABLE collateral_haircut ADD COLUMN asset_id BIGINT REFERENCES assets(id);
ALTER TABLE collateral_history ADD COLUMN asset_id BIGINT REFERENCES assets(id);
ALTER TABLE collateral_history ADD COLUMN security_id BIGINT REFERENCES security_master(id);
CREATE TABLE margin_recall (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), external_id VARCHAR(100) NOT NULL UNIQUE,
 amount NUMERIC(24,6) NOT NULL CHECK(amount>0), fulfilled_amount NUMERIC(24,6) NOT NULL DEFAULT 0,
 reason VARCHAR(500) NOT NULL, status VARCHAR(30) NOT NULL,
 request_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, due_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE recall (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), external_id VARCHAR(100) NOT NULL UNIQUE,
 quantity BIGINT NOT NULL CHECK(quantity>0), fulfilled_quantity BIGINT NOT NULL DEFAULT 0,
 reason VARCHAR(500) NOT NULL, status VARCHAR(30) NOT NULL,
 request_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, due_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE lending_fee (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), period_start DATE NOT NULL, period_end DATE NOT NULL,
 fee_rate NUMERIC(16,10) NOT NULL, fee_amount NUMERIC(24,6) NOT NULL, currency VARCHAR(3) NOT NULL DEFAULT 'INR',
 due_date DATE NOT NULL, paid_at TIMESTAMP WITH TIME ZONE, status VARCHAR(30) NOT NULL,
 UNIQUE(loan_id,period_start,period_end)
);
CREATE TABLE rebate (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), collateral_position_id BIGINT REFERENCES collateral_position(id),
 rebate_rate NUMERIC(16,10) NOT NULL, amount NUMERIC(24,6) NOT NULL, accrual_date DATE NOT NULL,
 next_payment_date DATE NOT NULL, status VARCHAR(30) NOT NULL, UNIQUE(loan_id,accrual_date)
);
CREATE TABLE rebate_payment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), rebate_id BIGINT NOT NULL UNIQUE REFERENCES rebate(id),
 payment_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, amount NUMERIC(24,6) NOT NULL
);
CREATE TABLE credit_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id), transaction_type VARCHAR(40) NOT NULL,
 old_limit NUMERIC(24,6) NOT NULL, new_limit NUMERIC(24,6) NOT NULL,
 credit_change NUMERIC(24,6) NOT NULL, utilized_before NUMERIC(24,6) NOT NULL, utilized_after NUMERIC(24,6) NOT NULL,
 available_before NUMERIC(24,6) NOT NULL, available_after NUMERIC(24,6) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Organization-level watchlists are shared by that organization's traders.
CREATE TABLE watchlist_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id), UNIQUE(organization_id,security_id)
);
CREATE TABLE notification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organization(id),
 type VARCHAR(80) NOT NULL, reference VARCHAR(120) NOT NULL, message VARCHAR(500) NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
