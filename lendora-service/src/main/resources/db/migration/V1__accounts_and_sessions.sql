CREATE TABLE auth_organization (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
 external_key VARCHAR(80) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL,
 type VARCHAR(20) NOT NULL CHECK(type IN ('LENDER','BORROWER')),
 registration_number VARCHAR(100) NOT NULL,
 country VARCHAR(80) NOT NULL,
 base_currency VARCHAR(3) NOT NULL,
 registered_address VARCHAR(500) NOT NULL,
 platform_organization_id BIGINT,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(type,registration_number)
);
CREATE TABLE auth_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES auth_organization(id),
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(300) NOT NULL,
 active BOOLEAN NOT NULL,
 failed_attempts INTEGER NOT NULL,
 locked_until TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE auth_session (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES auth_user(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_auth_session_user ON auth_session(user_id);
CREATE INDEX ix_auth_session_expiry ON auth_session(expires_at);
