ALTER TABLE loan ADD COLUMN fee_processed_through DATE;
ALTER TABLE loan ADD COLUMN fee_finalized BOOLEAN NOT NULL DEFAULT FALSE;

-- External accruals and bills remain under their original ownership.
UPDATE loan SET fee_processed_through = (
 SELECT MAX(historical_fees.entry_date) FROM (
   SELECT loan_id, period_end AS entry_date FROM lending_fee
   UNION ALL
   SELECT loan_id, entry_date FROM daily_accrual WHERE accrual_type = 'FEE'
 ) AS historical_fees WHERE historical_fees.loan_id = loan.id
);

CREATE TABLE lending_fee_day (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000000000000) PRIMARY KEY,
 loan_id BIGINT NOT NULL REFERENCES loan(id),
 accrual_date DATE NOT NULL,
 market_value NUMERIC(24,6) NOT NULL CHECK (market_value > 0),
 amount NUMERIC(24,6) NOT NULL CHECK (amount >= 0),
 billed BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE (loan_id, accrual_date)
);
