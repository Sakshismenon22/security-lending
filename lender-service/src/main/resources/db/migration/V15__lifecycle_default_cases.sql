CREATE TABLE lifecycle_default_case (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
  organization_id BIGINT NOT NULL REFERENCES organization(id),
  loan_id BIGINT NOT NULL REFERENCES loan(id),
  obligation_type VARCHAR(30) NOT NULL,
  obligation_id BIGINT NOT NULL,
  due_at TIMESTAMP WITH TIME ZONE NOT NULL,
  quantity BIGINT NOT NULL,
  exposure NUMERIC(24,6) NOT NULL,
  status VARCHAR(40) NOT NULL,
  version BIGINT NOT NULL,
  UNIQUE(organization_id, obligation_type, obligation_id, due_at)
);
CREATE INDEX lifecycle_default_case_loan ON lifecycle_default_case(organization_id, loan_id);
