CREATE TABLE collateral_liquidation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), default_id BIGINT NOT NULL REFERENCES loan_default(id),
 client_request_id VARCHAR(120) NOT NULL, sale_scope VARCHAR(64) NOT NULL, reference VARCHAR(120) NOT NULL,
 proceeds NUMERIC(24,6) NOT NULL CHECK(proceeds>0), lots TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(organization_id,client_request_id)
);
