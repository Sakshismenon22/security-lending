CREATE TABLE organization (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 external_id VARCHAR(100) NOT NULL UNIQUE,
 public_reference_id BIGINT NOT NULL UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE role (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_name VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL,
 role_id BIGINT NOT NULL REFERENCES role(id),
 active BOOLEAN NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(organization_id,email)
);

CREATE TABLE lender_account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id) UNIQUE,
 fee_received NUMERIC(24,6) NOT NULL,
 rebate_paid NUMERIC(24,6) NOT NULL,
 cash_collateral_held NUMERIC(24,6) NOT NULL CHECK(cash_collateral_held>=0)
);

CREATE TABLE borrower_connection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 external_id VARCHAR(100) NOT NULL,
 borrower_organization_id BIGINT NOT NULL,
 name VARCHAR(160) NOT NULL,
 active BOOLEAN NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(organization_id,external_id,borrower_organization_id)
);

CREATE TABLE security_master (
 id BIGINT PRIMARY KEY,
 symbol VARCHAR(40) NOT NULL,
 exchange VARCHAR(30) NOT NULL,
 name VARCHAR(160) NOT NULL,
 isin VARCHAR(20),
 currency VARCHAR(3) NOT NULL,
 price NUMERIC(24,6),
 price_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(symbol,exchange)
);

CREATE TABLE inventory_position (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id),
 total_quantity BIGINT NOT NULL CHECK(total_quantity>=0),
 reserved_quantity BIGINT NOT NULL CHECK(reserved_quantity>=0),
 loaned_quantity BIGINT NOT NULL CHECK(loaned_quantity>=0),
 UNIQUE(organization_id,security_id), CHECK(total_quantity>=reserved_quantity+loaned_quantity)
);

CREATE TABLE inventory_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 inventory_id BIGINT NOT NULL REFERENCES inventory_position(id),
 quantity BIGINT NOT NULL,
 type VARCHAR(40) NOT NULL,
 reference VARCHAR(160) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE msla (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 borrower_msla_id BIGINT NOT NULL,
 number VARCHAR(100) NOT NULL,
 status VARCHAR(40) NOT NULL,
 effective_date DATE NOT NULL,
 expiry_date DATE NOT NULL,
 credit_limit NUMERIC(24,6) NOT NULL,
 fee_rate NUMERIC(16,10) NOT NULL,
 rebate_rate NUMERIC(16,10) NOT NULL,
 coverage_ratio NUMERIC(12,6) NOT NULL,
 billing_frequency VARCHAR(20) NOT NULL,
 day_basis INTEGER NOT NULL,
 recall_allowed BOOLEAN NOT NULL,
 margin_hours INTEGER NOT NULL,
 recall_hours INTEGER NOT NULL,
 terms TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(connection_id,borrower_msla_id)
);

CREATE TABLE assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_name VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE collateral_haircut (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id),
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 asset_type VARCHAR(20) NOT NULL,
 security_id BIGINT REFERENCES security_master(id),
 haircut NUMERIC(12,8) NOT NULL CHECK(haircut>=0 AND haircut<1)
);

CREATE TABLE locate_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id),
 borrower_locate_id BIGINT NOT NULL,
 security_id BIGINT NOT NULL REFERENCES security_master(id),
 quantity BIGINT NOT NULL CHECK(quantity>0),
 approved_quantity BIGINT NOT NULL,
 status VARCHAR(40) NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(connection_id,borrower_locate_id)
);

CREATE TABLE reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id),
 locate_id BIGINT NOT NULL REFERENCES locate_request(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id),
 borrower_reservation_id BIGINT NOT NULL,
 quantity BIGINT NOT NULL CHECK(quantity>0),
 remaining_quantity BIGINT NOT NULL CHECK(remaining_quantity>=0),
 revision BIGINT NOT NULL,
 status VARCHAR(40) NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(connection_id,borrower_reservation_id), UNIQUE(locate_id)
);

CREATE TABLE loan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id),
 reservation_id BIGINT NOT NULL REFERENCES reservation(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id),
 borrower_loan_id BIGINT NOT NULL,
 quantity BIGINT NOT NULL CHECK(quantity>0),
 outstanding_quantity BIGINT NOT NULL CHECK(outstanding_quantity>=0),
 status VARCHAR(40) NOT NULL,
 settlement_reference VARCHAR(160),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 settled_at TIMESTAMP WITH TIME ZONE,
 closed_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(connection_id,borrower_loan_id)
);

CREATE TABLE collateral_position (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 msla_id BIGINT NOT NULL REFERENCES msla(id),
 loan_id BIGINT REFERENCES loan(id),
 borrower_loan_id BIGINT NOT NULL,
 borrower_position_id BIGINT NOT NULL,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 asset_type VARCHAR(20) NOT NULL,
 security_id BIGINT REFERENCES security_master(id),
 quantity BIGINT NOT NULL CHECK(quantity>=0),
 cash_amount NUMERIC(24,6) NOT NULL CHECK(cash_amount>=0),
 haircut NUMERIC(12,8) NOT NULL,
 status VARCHAR(40) NOT NULL,
 settlement_reference VARCHAR(160),
 margin_call_id BIGINT,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(connection_id,borrower_position_id), CHECK((asset_type='CASH' AND security_id IS NULL AND quantity=0 AND cash_amount>0) OR (asset_type='SECURITY' AND security_id IS NOT NULL AND quantity>0 AND cash_amount=0))
);

CREATE TABLE collateral_history (
