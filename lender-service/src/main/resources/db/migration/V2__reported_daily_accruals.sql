CREATE TABLE daily_accrual (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 connection_id BIGINT NOT NULL REFERENCES borrower_connection(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id), owner_reference_id BIGINT NOT NULL,
 source_version BIGINT NOT NULL, source_data TEXT NOT NULL, status VARCHAR(40) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, amount NUMERIC(24,6) NOT NULL,
 rate NUMERIC(16,10) NOT NULL, base_value NUMERIC(24,6) NOT NULL,
 entry_date DATE NOT NULL, accrual_type VARCHAR(20) NOT NULL,
 UNIQUE(organization_id,owner_reference_id)
);
