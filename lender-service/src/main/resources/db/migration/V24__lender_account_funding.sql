ALTER TABLE lender_account ADD COLUMN funding_balance NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK (funding_balance >= 0);
ALTER TABLE buyin_order ADD COLUMN lender_funds_reserved NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK (lender_funds_reserved >= 0);
ALTER TABLE buyin_loan_closeout ADD COLUMN lender_funds_applied NUMERIC(24,6) NOT NULL DEFAULT 0 CHECK (lender_funds_applied >= 0);

CREATE TABLE lender_deposit_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 client_request_id VARCHAR(120) NOT NULL,
 amount NUMERIC(24,6) NOT NULL CHECK (amount > 0),
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 approved_at TIMESTAMP WITH TIME ZONE,
 approved_by BIGINT REFERENCES users(id),
 UNIQUE (organization_id, client_request_id)
);
CREATE INDEX ix_lender_deposit_org_id ON lender_deposit_request(organization_id, id);
