ALTER TABLE msla ADD COLUMN rebate_settlement_frequency VARCHAR(20) DEFAULT 'AT_CLOSE' NOT NULL
 CHECK (rebate_settlement_frequency IN ('DAILY','WEEKLY','MONTHLY','AT_CLOSE'));

ALTER TABLE loan ADD COLUMN rebate_processed_through DATE;
-- Keep previously issued external rebates on their existing settlement path.
UPDATE loan SET rebate_processed_through = (
 SELECT MAX(rebate.accrual_date) FROM rebate WHERE rebate.loan_id = loan.id
);
ALTER TABLE rebate ADD COLUMN period_start DATE;
ALTER TABLE rebate ADD COLUMN period_end DATE;
ALTER TABLE rebate ADD COLUMN settlement_frequency VARCHAR(20);

CREATE TABLE rebate_daily_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
 loan_id BIGINT NOT NULL REFERENCES loan(id),
 accrual_date DATE NOT NULL,
 cash_balance NUMERIC(24,6) NOT NULL CHECK(cash_balance > 0),
 amount NUMERIC(24,6) NOT NULL CHECK(amount >= 0),
 settlement_reference_id BIGINT,
 UNIQUE(loan_id, accrual_date)
);
