CREATE TABLE buyin_order (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 default_id BIGINT NOT NULL REFERENCES loan_default(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id),
 security_id BIGINT NOT NULL REFERENCES security_master(id),
 buyin_request_id BIGINT NOT NULL REFERENCES lifecycle_request(id),
 execution_request_id BIGINT REFERENCES lifecycle_request(id),
 client_request_id VARCHAR(120) NOT NULL,
 type VARCHAR(20) NOT NULL,
 quantity BIGINT NOT NULL CHECK(quantity>0),
 limit_price NUMERIC(24,6),
 costs NUMERIC(24,6) NOT NULL CHECK(costs>=0),
 status VARCHAR(40) NOT NULL,
 failure_reason VARCHAR(1000),
 execution_price NUMERIC(24,6),
 quote_at TIMESTAMP WITH TIME ZONE,
 execution_reference VARCHAR(120) NOT NULL UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 filled_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(organization_id,client_request_id)
);
CREATE INDEX buyin_order_pending ON buyin_order(status,id);
ALTER TABLE buy_in ADD COLUMN inventory_received_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE buy_in ADD COLUMN inventory_reference VARCHAR(120);
CREATE UNIQUE INDEX buyin_inventory_reference ON buy_in(organization_id,inventory_reference);
