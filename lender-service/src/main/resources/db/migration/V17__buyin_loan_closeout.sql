ALTER TABLE buy_in ADD COLUMN closeout_quantity BIGINT NOT NULL DEFAULT 0;
CREATE TABLE buyin_loan_closeout (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organization(id),
 loan_id BIGINT NOT NULL REFERENCES loan(id),
 default_id BIGINT NOT NULL REFERENCES loan_default(id),
 quantity BIGINT NOT NULL,
 purchase_cost NUMERIC(24,6) NOT NULL,
 cash_collateral_applied NUMERIC(24,6) NOT NULL,
 cash_collateral_returned NUMERIC(24,6) NOT NULL,
 reference VARCHAR(120) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(organization_id,loan_id), UNIQUE(organization_id,reference)
);
